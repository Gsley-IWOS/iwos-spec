"""Protected-artefact integrity lock: SHA-256 of every protected file, committed with the files."""
from __future__ import annotations

import datetime as _dt
import glob
import hashlib
import re
from pathlib import Path

import yaml

from .config import Config

LOCK_SCHEMA_VERSION = "1.0.0"


def protected_files(cfg: Config) -> list[Path]:
    found: set[Path] = set()
    for pattern in cfg.protected:
        for rel in glob.glob(pattern, root_dir=cfg.root, recursive=True):
            path = cfg.root / rel
            if path.is_file():
                found.add(path)
    return sorted(found)


def glob_to_regex(pattern: str) -> "re.Pattern[str]":
    """Translate a path glob to a regular expression: `*` and `?` stay within one path segment, `**` spans segments."""
    out, i = "", 0
    while i < len(pattern):
        c = pattern[i]
        if pattern.startswith("**/", i):
            out += "(?:.*/)?"; i += 3
        elif pattern.startswith("**", i):
            out += ".*"; i += 2
        elif c == "*":
            out += "[^/]*"; i += 1
        elif c == "?":
            out += "[^/]"; i += 1
        else:
            out += re.escape(c); i += 1
    return re.compile("^" + out + "$")


def _matches(patterns: list[str], rel_path: str) -> list[str]:
    rel_path = rel_path.replace("\\", "/")
    return [p for p in patterns if glob_to_regex(p).match(rel_path)]


def matches_protected(cfg: Config, rel_path: str) -> list[str]:
    """Return the protected patterns a repository-relative path matches."""
    return _matches(cfg.protected, rel_path)


def matches_architecture(cfg: Config, rel_path: str) -> list[str]:
    return _matches(cfg.architecture, rel_path)


def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rel(cfg: Config, path: Path) -> str:
    return str(path.relative_to(cfg.root)).replace("\\", "/")


def current_entries(cfg: Config) -> list[dict]:
    return [{"path": rel(cfg, p), "sha256": sha256_of(p)} for p in protected_files(cfg)]


def build_lock(cfg: Config, today: str | None = None) -> dict:
    return {
        "schema_version": LOCK_SCHEMA_VERSION,
        "algorithm": "sha256",
        "generated_by": "iwos lock",
        "last_updated": today or _dt.date.today().isoformat(),
        "entries": current_entries(cfg),
    }


def read_lock(cfg: Config) -> dict | None:
    path = cfg.root / cfg.lock_file
    if not path.exists():
        return None
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or not isinstance(data.get("entries"), list):
        raise ValueError(f"{cfg.lock_file} is not a lock: expected a mapping with an entries list")
    return data


def write_lock(cfg: Config) -> Path:
    """Write the lock. Idempotent: the date is kept when the entries are unchanged."""
    if cfg.spec_validator_config is not None:
        return _write_spec_lock(cfg)
    path = cfg.root / cfg.lock_file
    lock = build_lock(cfg)
    previous = read_lock(cfg) if path.exists() else None
    if previous and previous.get("entries") == lock["entries"]:
        lock["last_updated"] = previous.get("last_updated", lock["last_updated"])
    path.parent.mkdir(parents=True, exist_ok=True)
    header = ("# IWOS Guard integrity lock. GENERATED by `iwos lock`; do not edit by hand.\n"
              "# Regenerate only in the same change that alters a protected artefact under valid authority.\n")
    path.write_text(header + yaml.safe_dump(lock, sort_keys=False), encoding="utf-8")
    return path


def _write_spec_lock(cfg: Config) -> Path:
    """The iwos-spec profile keeps the lock format of its own validator (MEM-008)."""
    import sys
    sys.path.insert(0, str(cfg.root / "tools" / "validate"))
    import validate as spec_validate  # type: ignore
    spec_cfg = yaml.safe_load(cfg.spec_validator_config.read_text(encoding="utf-8"))
    return spec_validate.write_lock(cfg.root, spec_cfg)


def check_lock(cfg: Config) -> list[str]:
    """Return integrity findings. Empty means the lock matches every protected artefact."""
    try:
        lock = read_lock(cfg)
    except ValueError as exc:
        return [str(exc)]
    if lock is None:
        return [f"lock {cfg.lock_file} is missing; run `iwos lock` under valid authority"]
    recorded = {e.get("path"): e.get("sha256") for e in lock["entries"] if isinstance(e, dict)}
    current = {e["path"]: e["sha256"] for e in current_entries(cfg)}
    findings = []
    for path, digest in current.items():
        if path not in recorded:
            findings.append(f"{path}: protected artefact is not recorded in the lock")
        elif recorded[path] != digest:
            findings.append(f"{path}: protected artefact differs from the digest in the lock")
    for path in sorted(set(recorded) - set(current)):
        findings.append(f"{path}: lock records a protected artefact that no longer exists")
    return findings
